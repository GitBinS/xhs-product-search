/* ⚠️ 不要用 `__dirname` 定位自带副本：实测 Obsidian 加载插件时它不等于插件目录（拿到的是别的路径）。
   可靠做法 = `this.manifest.dir`（Obsidian 给的插件目录，可能是相对 vault 的）+ vault 基路径。 */
function pluginDirs(plugin) {
  const out = [];
  const d = (plugin && plugin.manifest && plugin.manifest.dir) || "";
  if (d) {
    if (path.isAbsolute(d)) out.push(d);
    else {
      const base = plugin.app && plugin.app.vault && plugin.app.vault.adapter
        && typeof plugin.app.vault.adapter.getBasePath === "function"
        ? plugin.app.vault.adapter.getBasePath() : "";
      if (base) out.push(path.join(base, d));
    }
  }
  if (typeof __dirname === "string" && __dirname) out.push(__dirname);
  return out;
}
